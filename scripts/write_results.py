"""Rewrite the Results section of docs/PIPELINE.md from data/models/<freq>/metrics.json.

Called by train_models.py after training, so the docs always match the committed models.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from tagatrend.catalog import BY_SLUG  # noqa: E402
from tagatrend.config import MODEL_DIR  # noqa: E402

DOC = ROOT / "docs" / "PIPELINE.md"
ORDER = ["Ensemble", "TimesFM", "XGBoost", "MLP", "Mean of last 7", "Drift", "Naive"]
LABEL = {"daily": "Daily, 28 days ahead", "weekly": "Weekly, 12 weeks ahead"}


def signed(value):
    return f"{value:+.0f}%"


def section():
    lines = []
    for freq in ("weekly", "daily"):
        path = MODEL_DIR / freq / "metrics.json"
        if not path.exists():
            continue
        m = json.loads(path.read_text(encoding="utf-8"))
        overall = {r["model"]: r for r in m["overall"]}
        phase = {(r["model"], r["phase"]): r["skill_pct"] for r in m["by_phase"]}
        terms = ", ".join(BY_SLUG[s]["query"] for s in m["trends"] if s in BY_SLUG)
        lines += [f"**{LABEL[freq]}**: {m['origins']:,} forecast dates across {len(m['trends'])} terms ({terms}).", ""]
        lines += ["| Model | MAE (index points) | Skill vs last value | Rise | Peak | Decay | 80% band coverage |",
                  "|---|---:|---:|---:|---:|---:|---:|"]
        for name in ORDER:
            if name not in overall:
                continue
            r = overall[name]
            cover = "—" if name in ("Naive", "Drift", "Mean of last 7") else f"{100 * r['coverage_80']:.0f}%"
            skill = "baseline" if name == "Naive" else signed(r["skill_pct"])
            phases = ["—" if name == "Naive" else signed(phase.get((name, p), float("nan"))) for p in ("Rise", "Peak", "Decay")]
            lines.append(f"| {name} | {r['mae_index']:.2f} | {skill} | {' | '.join(phases)} | {cover} |")
        if m.get("folds"):
            mean = {k: sum(f["weights"].get(k, 0) for f in m["folds"]) / len(m["folds"]) for k in m["folds"][0]["weights"]}
            lines += ["", "Mean ensemble weights across folds: " + ", ".join(f"{k} {v:.2f}" for k, v in mean.items()) + "."]
        lines.append("")
    lines.append("Rise, Peak and Decay are skill against the last value in that phase. Regenerated by `scripts/train_models.py`.")
    return "\n".join(lines)


def main():
    text = DOC.read_text(encoding="utf-8")
    block = f"<!-- results:start -->\n{section()}\n<!-- results:end -->"
    text = re.sub(r"<!-- results:start -->.*?<!-- results:end -->", lambda _: block, text, flags=re.S)
    DOC.write_text(text, encoding="utf-8", newline="\n")
    print("docs/PIPELINE.md results updated")


if __name__ == "__main__":
    main()
